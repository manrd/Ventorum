def test_report_shows_heights(tmp_path):
    """A result with a h_m list gets a h [m] column; a result without one does not."""
    case_plain = load_case(_write_height_case(tmp_path / "plain_case.md", "plain_case", [0.0, 4.0]))
    case_height = load_case(
        _write_height_case(
            tmp_path / "height_case.md", "height_case", [0.0, 4.0], h_list=[1.5, 2.0]
        )
    )
    mod = _runner_module()
    text, _ = mod.build_report(tmp_path, [case_plain, case_height], [], [], "vlm")
    assert text.count("| alpha [deg] | h [m] |") == 1
    assert "| alpha [deg] | reference |" in text


