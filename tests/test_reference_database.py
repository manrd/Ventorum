def _run_runner(db, out, extra=()):
    env = {
        "PYTHONPATH": str(REPO),
        "MPLBACKEND": "Agg",
        "PATH": __import__("os").environ.get("PATH", ""),
        "SYSTEMROOT": __import__("os").environ.get("SYSTEMROOT", ""),
    }
    proc = subprocess.run(
        [sys.executable, str(RUNNER), "--db", str(db), "--out", str(out), *extra],
        capture_output=True,
        text=True,
        env=env,
        timeout=600,
    )
    return proc


def test_runner_writes_a_report(tmp_path):
    out = tmp_path / "report.md"
    proc = _run_runner(DATA_DIR, out)
    assert proc.returncode == 0, proc.stderr
    text = out.read_text(encoding="utf-8")
    assert "elliptic_synthetic" in text
    assert "synthetic" in text.lower()
    assert "| alpha" in text.lower() or "| Alpha" in text


