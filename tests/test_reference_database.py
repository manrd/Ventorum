def _write_height_case(path, case_id, alphas, h_list=None, height_point=None, scalar_h=None):
    """Write a synthetic case with a scalar height, a height list, or neither."""
    cla = analytic.elliptic_wing_cl_alpha(AR)
    vals = [cla * math.radians(a) for a in alphas]
    result_lines = [
        "[[results]]",
        'quantity = "CL"',
        f"alpha_deg = [{', '.join(f'{a:.1f}' for a in alphas)}]",
        f"values = [{', '.join(f'{v:.10f}' for v in vals)}]",
    ]
    if h_list is not None:
        result_lines.append(f"h_m = [{', '.join(f'{h:.3f}' for h in h_list)}]")
    if height_point is not None:
        result_lines.append(f"height_point = [{', '.join(f'{p:.3f}' for p in height_point)}]")
    result_lines.append('extraction = "table"')
    cond_h = f"\nh_m = {scalar_h:.3f}" if scalar_h is not None else ""
    results_text = "\n".join(result_lines)
    Path(path).write_text(
        f"# Case {case_id}\n\nFree text for people.\n\n```toml\n"
        f"[identity]\nid = \"{case_id}\"\ntitle = \"Synthetic height case\"\nentry_version = 1\n\n"
        "[source]\ncitation = \"Synthetic case for the height-per-point tests\"\n"
        'location = "Generated by the test"\ntype = "experiment"\ngrade = "C"\nsynthetic = true\n\n'
        "[geometry]\nspan_m = 6.0\nchord_m = 1.0\n\n"
        "[conditions]\nmach = 0.1\nreynolds = 1000000.0\nbeta_deg = 0.0"
        f'{cond_h}\ncorrections = "none (synthetic case)"\n\n'
        f"{results_text}\n\n"
        '[quality]\nnotes = "Synthetic case for the height-per-point tests."\n```\n',
        encoding="utf-8",
    )
    return Path(path)


def _runner_module():
    """Load validation/run_validation.py as a module (no subprocess, faster tests)."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("run_validation", REPO / "validation" / "run_validation.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


