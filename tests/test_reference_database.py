def test_height_list_matches_scalar(tmp_path):
    """The same height for every point gives the same Ventorum values as the scalar h_m."""
    alphas = [0.0, 4.0]
    case_scalar = load_case(_write_height_case(tmp_path / "h_scalar.md", "h_scalar", alphas, scalar_h=1.0))
    case_listed = load_case(
        _write_height_case(tmp_path / "h_listed.md", "h_listed", alphas, h_list=[1.0, 1.0])
    )
    mod = _runner_module()
    rows_scalar = mod.run_result(case_scalar, case_scalar.results[0], "vlm")
    rows_listed = mod.run_result(case_listed, case_listed.results[0], "vlm")
    assert all(r[7] is None for r in rows_scalar + rows_listed)
    for row_s, row_l in zip(rows_scalar, rows_listed):
        assert abs(row_s[3] - row_l[3]) <= 1e-12


def test_height_point_offset(tmp_path):
    """A height_point away from the reference point converts to the solved height."""
    import numpy as np

    import ventorum as vt
    from ventorum.aero.system import ground_normal

    alphas = [0.0, 4.0]
    h_list = [1.5, 1.5]
    height_point = [1.0, 0.0, 0.0]
    case = load_case(
        _write_height_case(
            tmp_path / "h_offset.md", "h_offset", alphas, h_list=h_list, height_point=height_point
        )
    )
    mod = _runner_module()
    rows = mod.run_result(case, case.results[0], "vlm")
    solve_ref = np.zeros(3)
    for row, alpha_deg, h_point in zip(rows, alphas, h_list):
        assert row[7] is None
        k = ground_normal(float(np.radians(alpha_deg)), float(np.radians(case.beta_deg)))
        h_ref = h_point + float((solve_ref - np.array(height_point)) @ k)
        # Independent check of the sign: x is aft, so with the nose up the
        # height point 1 m aft is lower, and the origin is higher by sin(alpha).
        assert abs(h_ref - (h_point + np.sin(np.radians(alpha_deg)))) <= 1e-12
        assert h_ref > 0.0
        condition = vt.FlightCondition(
            V_inf=case.mach * mod.SPEED_OF_SOUND_M_S,
            alpha=float(np.radians(alpha_deg)),
            beta=float(np.radians(case.beta_deg)),
            rho=mod.RHO_KG_M3,
            h=h_ref,
        )
        settings = vt.SolverSettings(solver_type="vlm", n_panels=mod.N_PANELS)
        direct = float(vt.analyze(case.aircraft, condition=condition, settings=settings).totals.CL)
        assert abs(row[3] - direct) <= 1e-12


