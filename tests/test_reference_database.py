AR = 6.0
ALPHAS_DEG = [-2.0, 0.0, 2.0, 4.0, 6.0, 8.0]


def _cl_values():
    """CL of an elliptic wing from Lanchester–Prandtl theory (never typed)."""
    cla = analytic.elliptic_wing_cl_alpha(AR)
    return [cla * math.radians(a) for a in ALPHAS_DEG]


def _sections_toml(n=25):
    """TOML rows for an elliptic planform with span 6 m and AR 6 (computed)."""
    root_chord = 4.0 / math.pi  # m, from S = b^2 / AR with an elliptic planform of span 6 m
    lines = []
    for i in range(n):
        eta = i / (n - 1)
        chord = max(root_chord * math.sqrt(max(1.0 - eta * eta, 0.0)), 1.0e-3 * root_chord)
        lines.append(f"  {{ y_frac = {eta:.6f}, chord_m = {chord:.6f} }},")
    return "\n".join(lines)


def _valid_toml(case_id="elliptic_synthetic", **overrides):
    """A valid TOML block; overrides replace whole lines by key prefix."""
    body = f"""[identity]
id = "{case_id}"
title = "Elliptic wing, synthetic theory case"
entry_version = 1

[source]
citation = "L. Prandtl, Tragflugeltheorie I/II, 1918-1919 (closed form, generated by the test)"
doi_or_url = "https://example.org/prandtl-1918"
location = "Closed form CL_alpha = a0 / (1 + a0 / (pi AR))"
type = "theory"
synthetic = true

[geometry]
span_m = 6.0
sections = [
{_sections_toml()}
]

[conditions]
mach = 0.1
reynolds = 1000000.0
beta_deg = 0.0
corrections = "none (synthetic case)"

[[results]]
quantity = "CL"
alpha_deg = [{", ".join(f"{a:.1f}" for a in ALPHAS_DEG)}]
values = [{", ".join(f"{v:.10f}" for v in _cl_values())}]
uncertainty = 0.02
uncertainty_kind = "absolute"
extraction = "table"

[quality]
notes = "Synthetic case for the parser tests."
"""
    for key, replacement in overrides.items():
        lines = []
        for line in body.splitlines():
            if line.strip().startswith(key):
                if replacement is not None:
                    lines.append(replacement)
            else:
                lines.append(line)
        body = "\n".join(lines) + "\n"
    return body


def _write_md(path, case_id="elliptic_synthetic", **overrides):
    path.write_text(
        f"# Case {case_id}\n\nFree text for people.\n\n```toml\n{_valid_toml(case_id, **overrides)}```\n",
        encoding="utf-8",
    )
    return path


def write_elliptic_synthetic(path):
    """Write the valid synthetic case (values computed from the formula)."""
    return _write_md(Path(path), "elliptic_synthetic")


def test_load_valid_case(tmp_path):
    path = write_elliptic_synthetic(tmp_path / "elliptic_synthetic.md")
    case = load_case(path)
    assert isinstance(case, ReferenceCase)
    assert case.id == "elliptic_synthetic"
    assert case.synthetic is True
    assert case.source_type == "theory"
    assert len(case.results) == 1
    res = case.results[0]
    assert res.quantity == "CL"
    assert list(res.alpha_deg) == pytest.approx(ALPHAS_DEG)
    assert list(res.values) == pytest.approx(_cl_values())
    assert res.abs_uncertainty == pytest.approx([0.02] * len(ALPHAS_DEG))
    assert case.aircraft.S_ref == pytest.approx(6.0, abs=0.05)
    assert case.aircraft.b_ref == pytest.approx(6.0)


