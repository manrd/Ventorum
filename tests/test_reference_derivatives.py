"""Tests for derivative quantities, the CL abscissa and slope entries of reference cases."""

import math
from pathlib import Path

import numpy as np
import pytest

import ventorum as vt
from ventorum.core.axes import transform_moments
from ventorum.reference.database import ReferenceError, load_case

REPO = Path(__file__).resolve().parents[1]
MOMENT_POINT = [0.25, 0.0, 0.0]


def _runner_module():
    """Load validation/run_validation.py as a module (no subprocess)."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("run_validation", REPO / "validation" / "run_validation.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _fmt_list(values):
    return "[" + ", ".join(repr(float(v)) for v in values) + "]"


def _write_case(path, result_lines, case_id=None, beta_deg=0.0):
    """Write a synthetic case of a rectangular wing (span 6 m, chord 1 m) with one result."""
    case_id = case_id or Path(path).stem
    body = "\n".join(result_lines)
    Path(path).write_text(
        f"# Case {case_id}\n\nSynthetic case for the derivative tests.\n\n```toml\n"
        f'[identity]\nid = "{case_id}"\ntitle = "Synthetic derivative case"\nentry_version = 1\n\n'
        '[source]\ncitation = "Synthetic case for the derivative tests"\n'
        'location = "Generated by the test"\ntype = "experiment"\ngrade = "C"\nsynthetic = true\n\n'
        "[geometry]\nspan_m = 6.0\nchord_m = 1.0\n\n"
        f"[conditions]\nmach = 0.1\nreynolds = 1000000.0\nbeta_deg = {beta_deg!r}\n"
        'corrections = "none (synthetic case)"\n\n'
        f"[[results]]\n{body}\n\n"
        '[quality]\nnotes = "Synthetic case for the derivative tests."\n```\n',
        encoding="utf-8",
    )
    return Path(path)


def _derivative_lines(quantity="Cl_beta", unit="1/deg", abscissa=None, values=None, extra=()):
    lines = [f'quantity = "{quantity}"']
    if abscissa is None:
        abscissa = ("alpha_deg", [4.0])
    if abscissa[0] is not None:
        lines.append(f"{abscissa[0]} = {_fmt_list(abscissa[1])}")
    vals = values if values is not None else [0.0] * len(abscissa[1])
    lines.append(f"values = {_fmt_list(vals)}")
    if unit is not None:
        lines.append(f'derivative_unit = "{unit}"')
    if quantity[:2] in ("Cl", "Cm", "Cn"):
        lines.append(f"moment_point = {_fmt_list(MOMENT_POINT)}")
    lines.extend(extra)
    lines.append('extraction = "table"')
    return lines


def _refused(tmp_path, name, lines, *fields):
    path = _write_case(tmp_path / f"{name}.md", lines)
    with pytest.raises(ReferenceError) as exc:
        load_case(path)
    message = str(exc.value)
    assert f"{name}.md" in message
    for item in fields:
        assert item in message, message
    return message


def _condition(case, alpha_deg, beta_deg, mod):
    return vt.FlightCondition(
        V_inf=case.mach * mod.SPEED_OF_SOUND_M_S,
        alpha=float(np.radians(alpha_deg)),
        beta=float(np.radians(beta_deg)),
        rho=mod.RHO_KG_M3,
    )


def _solve(case, alpha_deg, beta_deg, mod, moment_point=None):
    aircraft = case.aircraft.clone()
    if moment_point is not None:
        aircraft.ref_point = np.array(moment_point, dtype=float)
    settings = vt.SolverSettings(solver_type="vlm", n_panels=mod.N_PANELS)
    return vt.analyze(aircraft, condition=_condition(case, alpha_deg, beta_deg, mod), settings=settings)


def test_parse_derivative_quantity(tmp_path):
    """A derivative quantity loads with its unit, its axes (default stability) and its abscissa."""
    case = load_case(_write_case(tmp_path / "deriv_ok.md", _derivative_lines()))
    res = case.results[0]
    assert res.quantity == "Cl_beta"
    assert res.derivative_unit == "1/deg"
    assert res.axes == "stability"
    assert list(res.alpha_deg) == [4.0]
    assert res.CL is None
    assert res.slope_of is None
    assert list(res.moment_point) == MOMENT_POINT

    case = load_case(
        _write_case(
            tmp_path / "deriv_cl.md",
            _derivative_lines("CY_beta", "1/rad", ("CL", [0.1, 0.2]), extra=['axes = "body"']),
        )
    )
    res = case.results[0]
    assert res.axes == "body"
    assert list(res.CL) == [0.1, 0.2]
    assert list(res.alpha_deg) == []

    case = load_case(
        _write_case(
            tmp_path / "deriv_slope.md",
            _derivative_lines(abscissa=(None, [0.0]), extra=['slope_of = "CL"', "CL_range = [0.0, 0.4]"]),
        )
    )
    res = case.results[0]
    assert res.slope_of == "CL"
    assert list(res.CL_range) == [0.0, 0.4]
    assert len(res.values) == 1


def test_derivative_refusals(tmp_path):
    """The parser refuses the cases of decision 5 and names the file and the field."""
    _refused(tmp_path, "no_unit", _derivative_lines(unit=None), "derivative_unit")
    _refused(tmp_path, "bad_unit", _derivative_lines(unit="1/s"), "derivative_unit")
    _refused(tmp_path, "bad_variable", _derivative_lines(quantity="Cl_gamma"), "quantity", "Cl_gamma")
    _refused(tmp_path, "bad_coefficient", _derivative_lines(quantity="CDi_alpha"), "quantity", "CDi_alpha")
    _refused(tmp_path, "bad_axes", _derivative_lines(extra=['axes = "earth"']), "axes")
    _refused(
        tmp_path,
        "both_abscissas",
        _derivative_lines(extra=["CL = [0.2]"]),
        "alpha_deg",
        "CL",
    )
    _refused(tmp_path, "no_abscissa", _derivative_lines(abscissa=(None, [0.0])), "alpha_deg")
    _refused(
        tmp_path,
        "slope_two_values",
        _derivative_lines(abscissa=(None, [0.0, 0.0]), extra=['slope_of = "CL"', "CL_range = [0.0, 0.4]"]),
        "values",
    )
    _refused(
        tmp_path,
        "slope_no_range",
        _derivative_lines(abscissa=(None, [0.0]), extra=['slope_of = "CL"']),
        "CL_range",
    )
    _refused(
        tmp_path,
        "slope_bad_range",
        _derivative_lines(abscissa=(None, [0.0]), extra=['slope_of = "CL"', "CL_range = [0.4, 0.4]"]),
        "CL_range",
    )
    _refused(
        tmp_path,
        "slope_of_alpha",
        _derivative_lines(abscissa=(None, [0.0]), extra=['slope_of = "alpha"', "CL_range = [0.0, 0.4]"]),
        "slope_of",
    )
    _refused(tmp_path, "moment_no_point", [
        'quantity = "Cn_beta"', "alpha_deg = [4.0]", "values = [0.0]",
        'derivative_unit = "1/deg"', 'extraction = "table"',
    ], "moment_point")


def test_derivative_matches_central_difference(tmp_path):
    """The runner value of Cl_beta at alpha 4 deg equals a manual central difference (1e-12)."""
    mod = _runner_module()
    case = load_case(
        _write_case(tmp_path / "cd_check.md", _derivative_lines(unit="1/rad", abscissa=("alpha_deg", [4.0])))
    )
    rows = mod.run_result(case, case.results[0], "vlm")
    assert rows[0][7] is None, rows[0][7]
    plus = _solve(case, 4.0, 1.0, mod, MOMENT_POINT)
    minus = _solve(case, 4.0, -1.0, mod, MOMENT_POINT)
    step = math.radians(2.0)
    d_body = [
        (plus.totals.Cl - minus.totals.Cl) / step,
        (plus.totals.Cm - minus.totals.Cm) / step,
        (plus.totals.Cn - minus.totals.Cn) / step,
    ]
    d_stab = transform_moments(
        *d_body, math.radians(4.0), 0.0, "stability", b_ref=plus.b_ref, c_ref=plus.c_ref
    )
    assert abs(rows[0][3] - d_stab["Cl"]) <= 1e-12
    # A flat wing with lift: the rolling moment due to sideslip is negative.
    assert rows[0][3] < 0.0


def test_cl_abscissa(tmp_path):
    """The alpha found for a CL target gives that CL; a CL beyond the sweep range is not reached."""
    mod = _runner_module()
    targets = [0.25, 50.0]
    case = load_case(
        _write_case(tmp_path / "cl_abscissa.md", _derivative_lines(abscissa=("CL", targets)))
    )
    rows = mod.run_result(case, case.results[0], "vlm")
    first, second = rows
    assert first[7] is None, first[7]
    alpha_found = first[8]
    got_cl = _solve(case, alpha_found, 0.0, mod).totals.CL
    assert abs(got_cl - targets[0]) <= 1e-6
    assert second[3] is None
    assert second[7] is not None and second[7].startswith("not reached")
    text, counted = mod.build_report(tmp_path, [case], [], [], "vlm")
    assert "not reached" in text
    assert "| CL | alpha [deg] | reference |" in text


def test_slope_entry(tmp_path):
    """A slope entry whose reference is the Ventorum slope itself gives a zero difference."""
    mod = _runner_module()
    extra = ['slope_of = "CL"', "CL_range = [0.0, 0.4]"]
    probe = load_case(
        _write_case(tmp_path / "slope_probe.md", _derivative_lines(abscissa=(None, [0.0]), extra=extra))
    )
    rows = mod.run_result(probe, probe.results[0], "vlm")
    assert rows[0][7] is None, rows[0][7]
    slope = rows[0][3]
    assert math.isfinite(slope)
    case = load_case(
        _write_case(
            tmp_path / "slope_self.md",
            _derivative_lines(abscissa=(None, [0.0]), values=[slope], extra=extra),
        )
    )
    rows = mod.run_result(case, case.results[0], "vlm")
    assert abs(rows[0][4]) <= 1e-9
    residual = rows[0][8]
    assert residual >= 0.0
    text, _ = mod.build_report(tmp_path, [case], [], [], "vlm")
    assert "fitted slope" in text
    assert "largest residual" in text
    assert f"{residual:.3e}" in text


def test_units_deg_rad(tmp_path):
    """The same reference in 1/deg and in 1/rad gives the same comparison."""
    mod = _runner_module()
    alphas = [2.0, 4.0]
    per_rad = [-0.01, -0.02]
    per_deg = [v * math.pi / 180.0 for v in per_rad]
    unc_rad = 0.05
    case_rad = load_case(
        _write_case(
            tmp_path / "unit_rad.md",
            _derivative_lines(
                unit="1/rad", abscissa=("alpha_deg", alphas), values=per_rad,
                extra=[f"uncertainty = {unc_rad!r}", 'uncertainty_kind = "absolute"'],
            ),
        )
    )
    case_deg = load_case(
        _write_case(
            tmp_path / "unit_deg.md",
            _derivative_lines(
                unit="1/deg", abscissa=("alpha_deg", alphas), values=per_deg,
                extra=[f"uncertainty = {unc_rad * math.pi / 180.0!r}", 'uncertainty_kind = "absolute"'],
            ),
        )
    )
    rows_rad = mod.run_result(case_rad, case_rad.results[0], "vlm")
    rows_deg = mod.run_result(case_deg, case_deg.results[0], "vlm")
    scale = math.pi / 180.0
    for r_rad, r_deg in zip(rows_rad, rows_deg):
        assert r_rad[7] is None and r_deg[7] is None
        assert r_deg[3] == pytest.approx(r_rad[3] * scale, rel=1e-12, abs=1e-15)
        assert r_deg[4] == pytest.approx(r_rad[4] * scale, rel=1e-9, abs=1e-15)
        assert r_deg[5] == r_rad[5]


def test_old_cases_unchanged(tmp_path):
    """An existing-format case gives the same report lines as before the change."""
    mod = _runner_module()
    alphas = [0.0, 4.0]
    lines = [
        'quantity = "CL"',
        f"alpha_deg = {_fmt_list(alphas)}",
        "values = [0.0, 0.3]",
        "uncertainty = 0.01",
        'uncertainty_kind = "absolute"',
        'extraction = "table"',
    ]
    case = load_case(_write_case(tmp_path / "old_cl.md", lines))
    moment_lines = [
        'quantity = "Cm"',
        f"alpha_deg = {_fmt_list(alphas)}",
        "values = [0.0, -0.05]",
        f"moment_point = {_fmt_list(MOMENT_POINT)}",
        'extraction = "digitised"',
        "digitising_error = 0.002",
    ]
    case_m = load_case(_write_case(tmp_path / "old_cm.md", moment_lines))
    text, counted = mod.build_report(tmp_path, [case, case_m], [], [], "vlm")
    expected = [
        "### CL (table)",
        "| alpha [deg] | reference | uncertainty | Ventorum | difference | inside |",
        "|---|---|---|---|---|---|",
        "### Cm (digitised, moment point [0.25, 0, 0] m)",
    ]
    for alpha_deg, ref in zip(alphas, [0.0, 0.3]):
        got = float(_solve(case, alpha_deg, 0.0, mod).totals.CL)
        diff = got - ref
        inside = "yes" if abs(diff) <= 0.01 else "no"
        expected.append(f"| {alpha_deg:g} | {ref:.6f} | {0.01:.6f} | {got:.6f} | {diff:+.6f} | {inside} |")
    for alpha_deg, ref in zip(alphas, [0.0, -0.05]):
        got = float(_solve(case_m, alpha_deg, 0.0, mod, MOMENT_POINT).totals.Cm)
        expected.append(f"| {alpha_deg:g} | {ref:.6f} | n/a | {got:.6f} | {got - ref:+.6f} | n/a |")
    for line in expected:
        assert line in text.splitlines(), line
    assert counted["synthetic_points"] == 4
    assert counted["points"] == 0
